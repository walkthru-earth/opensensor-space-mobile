// The shared core model of what a station measures (#183): board templates, app profiles, datastreams,
// observed properties, scales and the station that joins them. Pure commonMain with kotlinx
// serialization parsing of the stac-opensensor v0.1.0 board template, the app's own profile JSON and
// the station Collection. The bundled templates and profiles under `bundled/` are raw JSON files, so a
// new firmware digest is a file swap with no code change (#184). See [BundleFiles].
plugins {
    id("opensensor.kmp.library")
    alias(libs.plugins.kotlin.serialization)
}

/**
 * Embeds every `*.json` file under [source] as a Kotlin string, so common code on Android and iOS reads
 * the bundled templates and profiles without a resource API. The output is the internal object
 * `BundledFiles` with one entry per file, keyed by its path under [source] such as
 * `templates/cores3-telemetry-v5.json`.
 */
abstract class BundleFiles : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val source: DirectoryProperty

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun bundle() {
        val root = source.get().asFile
        val files = root.walkTopDown().filter { it.isFile && it.extension == "json" }.sortedBy { it.relativeTo(root).invariantSeparatorsPath }
        val entries = files.joinToString("\n") { file ->
            // Short chunks keep every literal far below the JVM constant pool limit of 65535 bytes.
            val chunks = file.readText().chunked(CHUNK).joinToString(",\n") { "            \"${escape(it)}\"" }
            "        \"${file.relativeTo(root).invariantSeparatorsPath}\" to listOf(\n$chunks,\n        ).joinToString(\"\"),"
        }
        val dir = output.get().asFile.resolve("space/opensensor/model")
        dir.mkdirs()
        dir.resolve("BundledFiles.kt").writeText(
            """
            |// Generated by the bundleFiles task from core/model/bundled. Do not edit.
            |package space.opensensor.model
            |
            |internal object BundledFiles {
            |    val files: Map<String, String> = mapOf(
            |$entries
            |    )
            |}
            |
            """.trimMargin(),
        )
    }

    private fun escape(text: String): String = buildString {
        text.forEach { c ->
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                // Non-ASCII as \uXXXX, so a chunk boundary inside a surrogate pair stays valid.
                else -> if (c.code in 0x20..0x7e) append(c) else append("\\u").append(c.code.toString(16).padStart(4, '0'))
            }
        }
    }

    private companion object {
        const val CHUNK = 8000
    }
}

val bundleFiles = tasks.register<BundleFiles>("bundleFiles") {
    source.set(layout.projectDirectory.dir("bundled"))
    output.set(layout.buildDirectory.dir("generated/bundled/commonMain/kotlin"))
}

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(bundleFiles.map { it.output })
            dependencies {
                implementation(libs.kotlinx.serialization.json)
            }
        }
    }
}
